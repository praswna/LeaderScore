export function sampleData(): Data {
  const leaders: Leader[] = [];
  const events: LeaderEvent[] = [];
  for (const [[id, name, country, dynasty, role, start, end], evs, summary] of SAMPLE) {
    const scored = evs.every(([, , s]) => s !== null);
    leaders.push({ id, name, country, dynasty, role, start, end, summary, scoredAt: scored ? "2026-10-14" : "" });
    evs.forEach(([year, title, score], i) => {
      events.push({ id: `${id}-${i + 1}`, leaderId: id, year, title, description: "", score, reason: "" });
    });
  }
  return { leaders, events };
}
